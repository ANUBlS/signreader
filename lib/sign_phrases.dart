// Перевод кода знака (нумерация ПДД Азербайджана / ГОСТ, они совпадают)
// в короткую русскую фразу для озвучки.
//
// Поддерживаемые форматы меток из labels.txt:
//   3_24_n60      (RTSD)
//   3.24_60       (наш формат для азербайджанских данных)
//   3.24|Своя фраза для озвучки     (ручное переопределение после "|")

class SignLabel {
  final String code; // нормализованный код, например "3.24"
  final int? number; // значение, например 60
  final String raw;
  final String? phrase; // фраза для озвучки (null = не озвучивать)
  const SignLabel(this.raw, this.code, this.number, this.phrase);

  String get short => number != null ? '$code ($number)' : code;
}

class SignLabels {
  final List<SignLabel> items;
  SignLabels(this.items);

  int get length => items.length;
  SignLabel? operator [](int i) => (i >= 0 && i < items.length) ? items[i] : null;

  static SignLabels parse(String text, {bool speakPlates = false}) {
    final out = <SignLabel>[];
    for (final line in text.split(RegExp(r'\r?\n'))) {
      final l = line.trim();
      if (l.isEmpty || l.startsWith('#')) continue;
      out.add(_parseOne(l, speakPlates));
    }
    return SignLabels(out);
  }

  static SignLabel _parseOne(String line, bool speakPlates) {
    String? custom;
    var name = line;
    final bar = line.indexOf('|');
    if (bar >= 0) {
      name = line.substring(0, bar).trim();
      custom = line.substring(bar + 1).trim();
    }

    String code;
    int? number;
    if (name.contains('.')) {
      // Наш формат: "3.24_60" или "3.24"
      final parts = name.split('_');
      code = parts[0];
      if (parts.length > 1) number = int.tryParse(parts[1].replaceAll(RegExp(r'\D'), ''));
    } else {
      // RTSD: "3_24_n60", "1_11_1", "5_19_1"
      final codeParts = <String>[];
      for (final t in name.split('_')) {
        if (RegExp(r'^\d+$').hasMatch(t)) {
          codeParts.add(t);
        } else {
          final m = RegExp(r'^[nN](\d+)').firstMatch(t);
          if (m != null) number = int.parse(m.group(1)!);
          break;
        }
      }
      code = codeParts.join('.');
    }

    if (custom != null) {
      return SignLabel(name, code, number, custom.isEmpty ? null : custom);
    }
    if (!speakPlates && code.startsWith('8')) {
      return SignLabel(name, code, number, null);
    }
    return SignLabel(name, code, number, _phrase(code, number));
  }

  static String? _phrase(String code, int? n) {
    var key = code;
    while (key.isNotEmpty) {
      final t = _table[key];
      if (t != null) return _fill(t, n);
      final dot = key.lastIndexOf('.');
      if (dot < 0) break;
      key = key.substring(0, dot);
    }
    final group = code.split('.').first;
    return _groups[group];
  }

  static String _fill(String t, int? n) {
    if (t.contains('{n}')) {
      return n != null ? t.replaceAll('{n}', '$n') : t.replaceAll(' {n}', '').replaceAll('{n}', '');
    }
    return t;
  }

